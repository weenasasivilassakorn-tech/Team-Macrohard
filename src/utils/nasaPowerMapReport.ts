import type { AppLanguage, NasaWeatherTelemetry } from '../types/cropshield';
import type { NasaMapLayerId, NasaPowerGridCell } from './nasaPowerMap';
import { NASA_MAP_LAYERS, computeNasaPowerGridCell } from './nasaPowerMap';
import { computeParcelGeometryFromRai } from './offlineMapGeometry';

export interface NasaMapReportInput {
  lang: AppLanguage;
  plotTitle: string;
  lat: number;
  lon: number;
  areaRai: number;
  provinceLabel?: string;
  activeLayer: NasaMapLayerId;
  selectedCell?: NasaPowerGridCell;
  telemetry?: NasaWeatherTelemetry;
  soilMoisturePercent: number;
  tempC: number;
  precipLabel: string;
  humidityPercent: number;
  elevationMeters?: number;
  healthScore?: number;
  riskSummaryText?: string;
  dataSourceLabel?: string;
}

export interface NasaMapPdfPayload {
  lang: AppLanguage;
  filename: string;
  title: string;
  subtitle: string;
  generatedAtLabel: string;
  plotTitle: string;
  provinceLabel: string;
  coordLabel: string;
  googleMapsUrl: string;
  areaLabel: string;
  parcelSizeLabel: string;
  merraCellId: string;
  merraBoundsLabel: string;
  merraSizeLabel: string;
  layerLabel: string;
  nasaProductCode: string;
  dataSourceLabel: string;
  healthScoreLabel: string;
  riskSummaryText: string;
  metrics: {
    soilWetness: string;
    tempC: string;
    precip: string;
    humidity: string;
    elevation: string;
  };
  observations: Array<{
    dateLabel: string;
    tempLabel: string;
    precipLabel: string;
    humidityLabel: string;
  }>;
}

export function buildNasaMapShareText(input: NasaMapReportInput): string {
  const isTh = input.lang === 'th';
  const cell = input.selectedCell ?? computeNasaPowerGridCell(input.lat, input.lon, true);
  const layerMeta =
    NASA_MAP_LAYERS.find((l) => l.id === input.activeLayer) ?? NASA_MAP_LAYERS[0];
  const googleMapsUrl = `https://maps.google.com/?q=${input.lat.toFixed(4)},${input.lon.toFixed(4)}`;
  const provinceText = input.provinceLabel ? ` (${input.provinceLabel})` : '';
  const scoreLine =
    input.healthScore !== undefined
      ? isTh
        ? `\n• คะแนนสุขภาพแปลง NASA: ${input.healthScore}/100`
        : `\n• NASA Plot Health Score: ${input.healthScore}/100`
      : '';
  const riskLine = input.riskSummaryText
    ? isTh
      ? `\n• แนวโน้ม 7 วัน: ${input.riskSummaryText}`
      : `\n• 7-Day Outlook: ${input.riskSummaryText}`
    : '';
  const elevLine =
    input.elevationMeters !== undefined
      ? isTh
        ? ` · ความสูง ${input.elevationMeters} ม.`
        : ` · Elev ${input.elevationMeters}m`
      : '';

  if (isTh) {
    return [
      `🛰️ รายงานแผนที่ดาวเทียม NASA POWER — ${input.plotTitle}${provinceText}`,
      `📍 พิกัดแปลง: ${input.lat.toFixed(4)}°N, ${input.lon.toFixed(4)}°E (${input.areaRai} ไร่${elevLine})`,
      `🗺️ ดูพิกัดบนแผนที่: ${googleMapsUrl}`,
      `🔲 กริด NASA MERRA-2: ${cell.id} (${layerMeta.labelTh})`,
      `🌡️ ข้อมูล NASA POWER:${scoreLine}${riskLine}`,
      `• ความชื้นผิวดิน (GWETTOP): ${input.soilMoisturePercent}%`,
      `• อุณหภูมิเฉลี่ย (T2M): ${input.tempC}°C`,
      `• ปริมาณฝน (PRECTOTCORR): ${input.precipLabel}`,
      `• ความชื้นสัมพัทธ์ (RH2M): ${input.humidityPercent}%`,
      `— ส่งจากระบบ CropShield (NASA POWER Data)`,
    ].join('\n');
  }

  return [
    `🛰️ CropShield NASA POWER Map Report — ${input.plotTitle}${provinceText}`,
    `📍 Plot Coordinates: ${input.lat.toFixed(4)}°N, ${input.lon.toFixed(4)}°E (${input.areaRai} Rai${elevLine})`,
    `🗺️ Map Location: ${googleMapsUrl}`,
    `🔲 MERRA-2 Grid Cell: ${cell.id} (${layerMeta.labelEn})`,
    `🌡️ NASA POWER Telemetry:${scoreLine}${riskLine}`,
    `• Surface Soil Wetness (GWETTOP): ${input.soilMoisturePercent}%`,
    `• Mean Temp (T2M): ${input.tempC}°C`,
    `• Precipitation (PRECTOTCORR): ${input.precipLabel}`,
    `• Relative Humidity (RH2M): ${input.humidityPercent}%`,
    `— Generated by CropShield (NASA POWER Data)`,
  ].join('\n');
}

export function buildNasaMapPdfPayload(
  input: NasaMapReportInput,
  now: Date = new Date()
): NasaMapPdfPayload {
  const isTh = input.lang === 'th';
  const cell = input.selectedCell ?? computeNasaPowerGridCell(input.lat, input.lon, true);
  const parcel = computeParcelGeometryFromRai(input.lat, input.lon, input.areaRai);
  const layerMeta =
    NASA_MAP_LAYERS.find((l) => l.id === input.activeLayer) ?? NASA_MAP_LAYERS[0];

  const safeName =
    input.plotTitle
      .replace(/[^a-zA-Z0-9ก-๙_-]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 32) || 'plot';
  const datePart = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, '0')}${String(
    now.getDate()
  ).padStart(2, '0')}`;

  const generatedAtLabel = now.toLocaleString(isTh ? 'th-TH' : 'en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

  const observations = (input.telemetry?.observations ?? []).slice(-7).map((obs) => ({
    dateLabel: obs.labelShort,
    tempLabel: `${obs.tempC}°C`,
    precipLabel: `${obs.precipMm} mm`,
    humidityLabel: `${obs.humidityPercent}%`,
  }));

  return {
    lang: input.lang,
    filename: `cropshield-nasa-map-${safeName}-${datePart}.pdf`,
    title: isTh
      ? 'รายงานแผนที่ดาวเทียมและข้อมูลจุดพิกัด NASA POWER'
      : 'NASA POWER Satellite Map & Point Telemetry Report',
    subtitle: isTh
      ? 'ข้อมูลภูมิอากาศและดินระดับกริด MERRA-2 สำหรับเกษตรกรและเจ้าหน้าที่ ธ.ก.ส.'
      : 'MERRA-2 Gridded Agroclimatology & Parcel Coordinates Report',
    generatedAtLabel,
    plotTitle: input.plotTitle,
    provinceLabel: input.provinceLabel || (isTh ? 'ประเทศไทย' : 'Thailand'),
    coordLabel: `${input.lat.toFixed(4)}°N, ${input.lon.toFixed(4)}°E`,
    googleMapsUrl: `https://maps.google.com/?q=${input.lat.toFixed(4)},${input.lon.toFixed(4)}`,
    areaLabel: `${input.areaRai} ${isTh ? 'ไร่' : 'Rai'}`,
    parcelSizeLabel: `~${parcel.widthMeters}m × ${parcel.heightMeters}m`,
    merraCellId: cell.id,
    merraBoundsLabel: `${cell.southLat.toFixed(2)}°–${cell.northLat.toFixed(2)}°N, ${cell.westLon.toFixed(2)}°–${cell.eastLon.toFixed(2)}°E`,
    merraSizeLabel: `~${cell.heightKm} × ${cell.widthKm} ${isTh ? 'กม.' : 'km'}`,
    layerLabel: isTh ? layerMeta.labelTh : layerMeta.labelEn,
    nasaProductCode: layerMeta.nasaProductCode,
    dataSourceLabel:
      input.dataSourceLabel ||
      input.telemetry?.sourceTag ||
      'NASA POWER · T2M / PRECTOTCORR / RH2M / GWETTOP',
    healthScoreLabel:
      input.healthScore !== undefined ? `${input.healthScore}/100` : 'N/A',
    riskSummaryText:
      input.riskSummaryText ||
      (isTh
        ? 'ติดตามความชื้นดินและสภาพอากาศล่วงหน้า 7 วันจากพิกัดดาวเทียม'
        : '7-day satellite soil moisture & weather outlook monitoring'),
    metrics: {
      soilWetness: `${input.soilMoisturePercent}%`,
      tempC: `${input.tempC}°C`,
      precip: input.precipLabel,
      humidity: `${input.humidityPercent}%`,
      elevation:
        input.elevationMeters !== undefined
          ? `${input.elevationMeters} m`
          : isTh
            ? 'ไม่ระบุ'
            : 'N/A',
    },
    observations,
  };
}

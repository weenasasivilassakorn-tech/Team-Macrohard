export function getRiskLabel(riskLevel: RiskLevel, lang: AppLanguage): string {
  if (lang === 'en') {
    switch (riskLevel) {
      case 'low':
        return 'Low Risk (Green)';
      case 'watch':
        return 'Watch (Yellow)';
      case 'critical':
        return 'Critical (Red)';
    }
  }
  switch (riskLevel) {
    case 'low':
      return 'ความเสี่ยงต่ำ (เขียว)';
    case 'watch':
      return 'เฝ้าระวัง (เหลือง)';
    case 'critical':
      return 'วิกฤต (แดง)';
  }
}

export function getScenarioLabel(scenario: ScenarioType, lang: AppLanguage): string {
  return APP_COPY[lang].forecast.scenarios[scenario];
}
